import type {ProjectSources} from "./projectSources";

export interface GeneratedSource {
    readonly file: string;
    readonly source: string;
}

export interface GeneratorOutput {
    readonly sources: readonly GeneratedSource[];
    readonly warnings: readonly string[];
}

export interface ProjectGenerator {
    readonly name: string;
    readonly version: number;
    readonly files: readonly string[];
    generate(project: ProjectSources): GeneratorOutput;
}

export interface GeneratedFileStamp {
    readonly generator: string;
    readonly version: number;
}

const HEADER_PATTERN = /^\/\/ Generated by jsengine (\S+) v(\d+)\./;

export function generatedFileHeader(generator: string, version: number): string {
    return `// Generated by jsengine ${generator} v${version}. Do not edit; run jsengine generate.`;
}

export function generatedFileStamp(text: string): GeneratedFileStamp | undefined {
    const match = HEADER_PATTERN.exec(text);
    return match === null ? undefined : {generator: match[1], version: Number(match[2])};
}
