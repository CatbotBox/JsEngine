export const ASCII_PIXEL_FONT_WIDTH_PX = 8;
export const ASCII_PIXEL_FONT_HEIGHT_PX = 16;

const SOURCE_ROW_REPEAT = ASCII_PIXEL_FONT_HEIGHT_PX / FONT8X8_BASIC_GLYPH_SIZE_PX;
const HALF_GLYPH_HEIGHT_PX = ASCII_PIXEL_FONT_HEIGHT_PX / 2;
const FULL_ROW_BITS = 0xFF;
const EMPTY_ROW_BITS = 0x00;

const UPPER_HALF_BLOCK_CODE_POINT = 0x2580;
const LOWER_HALF_BLOCK_CODE_POINT = 0x2584;
const FULL_BLOCK_CODE_POINT = 0x2588;
const LIGHT_SHADE_CODE_POINT = 0x2591;
const MEDIUM_SHADE_CODE_POINT = 0x2592;
const DARK_SHADE_CODE_POINT = 0x2593;

const LIGHT_SHADE_ROW_BITS: readonly number[] = [0x88, 0x22];
const MEDIUM_SHADE_ROW_BITS: readonly number[] = [0xAA, 0x55];
const DARK_SHADE_ROW_BITS: readonly number[] = [0x77, 0xDD];

function repeatedRows(sourceRows: readonly number[]): number[] {
    return sourceRows.flatMap(row => new Array<number>(SOURCE_ROW_REPEAT).fill(row));
}

function blockRows(firstLitRow: number, endLitRow: number): number[] {
    return Array.from({length: ASCII_PIXEL_FONT_HEIGHT_PX}, (_, row) => row >= firstLitRow && row < endLitRow ? FULL_ROW_BITS : EMPTY_ROW_BITS);
}

function alternatingRows(pattern: readonly number[]): number[] {
    return Array.from({length: ASCII_PIXEL_FONT_HEIGHT_PX}, (_, row) => pattern[row % pattern.length]);
}

function asciiPixelFontGlyphs(): PixelFontGlyph[] {
    const glyphs: PixelFontGlyph[] = FONT8X8_BASIC_PUBLIC_DOMAIN_ROWS.map((rows, index) =>
        [FONT8X8_BASIC_FIRST_CODE_POINT + index, repeatedRows(rows)]);
    glyphs.push(
        [UPPER_HALF_BLOCK_CODE_POINT, blockRows(0, HALF_GLYPH_HEIGHT_PX)],
        [LOWER_HALF_BLOCK_CODE_POINT, blockRows(HALF_GLYPH_HEIGHT_PX, ASCII_PIXEL_FONT_HEIGHT_PX)],
        [FULL_BLOCK_CODE_POINT, blockRows(0, ASCII_PIXEL_FONT_HEIGHT_PX)],
        [LIGHT_SHADE_CODE_POINT, alternatingRows(LIGHT_SHADE_ROW_BITS)],
        [MEDIUM_SHADE_CODE_POINT, alternatingRows(MEDIUM_SHADE_ROW_BITS)],
        [DARK_SHADE_CODE_POINT, alternatingRows(DARK_SHADE_ROW_BITS)],
    );
    return glyphs;
}

export const ASCII_PIXEL_FONT = new PixelFont(ASCII_PIXEL_FONT_WIDTH_PX, ASCII_PIXEL_FONT_HEIGHT_PX, asciiPixelFontGlyphs());
