function toPosix(path: string): string {
    return path.replace(/\\/g, "/");
}

function isInside(directory: string, target: string): boolean {
    const path = relative(directory, target);
    return path !== "" && !path.startsWith("..") && !isAbsolute(path);
}

function compareText(a: string, b: string): number {
    return a < b ? -1 : a > b ? 1 : 0;
}

function isProjectSourceFile(name: string): boolean {
    const isSource = SOURCE_EXTENSION_PATTERN.test(name);
    const isExcluded = name === GENERATED_FILE_NAME || EXCLUDED_FILE_SUFFIXES.some(suffix => name.endsWith(suffix));
    return isSource && !isExcluded;
}

export function discoverProjectFiles(projectFolder: string): string[] {
    const found: string[] = [];
    const visit = (directory: string): void => {
        for (const entry of readdirSync(directory, {withFileTypes: true})) {
            const path = join(directory, entry.name);
            if (entry.isDirectory()) {
                if (!EXCLUDED_DIRECTORY_NAMES.has(entry.name)) visit(path);
            } else if (isProjectSourceFile(entry.name)) {
                found.push(path);
            }
        }
    };
    visit(projectFolder);
    return found.sort((a, b) => compareText(toPosix(relative(projectFolder, a)), toPosix(relative(projectFolder, b))));
}

